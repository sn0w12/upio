use std::env;
use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

fn main() {
    if let Err(e) = generate_icons() {
        panic!("icon generation failed: {e}");
    }
    windows_resource();
}

fn windows_resource() {
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    println!("cargo:rerun-if-changed=assets/app-icons/icon.ico");

    let version = env::var("CARGO_PKG_VERSION").unwrap_or_default();
    let mut parts = version
        .split('.')
        .map(|part| part.parse::<u64>().unwrap_or(0));
    let major = parts.next().unwrap_or(0);
    let minor = parts.next().unwrap_or(0);
    let patch = parts.next().unwrap_or(0);
    let packed = (major << 48) | (minor << 32) | (patch << 16);

    let mut resource = winresource::WindowsResource::new();
    resource
        .set_icon("assets/app-icons/icon.ico")
        .set("ProductName", "upio")
        .set("FileDescription", "upio")
        .set("InternalName", "upio.exe")
        .set("OriginalFilename", "upio.exe")
        .set_version_info(winresource::VersionInfo::FILEVERSION, packed)
        .set_version_info(winresource::VersionInfo::PRODUCTVERSION, packed);
    resource
        .compile()
        .expect("embed Windows icon and version info");
}

fn generate_icons() -> Result<(), Box<dyn std::error::Error>> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let icons_dir = manifest_dir.join("assets/icons");
    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    let out_file = out_dir.join("icons.rs");

    println!("cargo:rerun-if-changed={}", icons_dir.display());

    let svg_paths = collect_svgs(&icons_dir)?;
    let mut out = String::from("// @generated by build.rs — do not edit\n");
    for path in &svg_paths {
        emit_icon(&mut out, path)?;
    }

    fs::write(&out_file, out)?;
    Ok(())
}

fn collect_svgs(dir: &Path) -> io::Result<Vec<PathBuf>> {
    let mut paths: Vec<PathBuf> = fs::read_dir(dir)?
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("svg"))
        .collect();
    paths.sort();
    Ok(paths)
}

fn emit_icon(out: &mut String, path: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let stem = path
        .file_stem()
        .and_then(|s| s.to_str())
        .ok_or_else(|| format!("non-utf8 filename: {}", path.display()))?;
    let ident = to_screaming_snake(stem);

    let svg = fs::read_to_string(path)?;
    let (view, body) =
        parse_svg(&svg).ok_or_else(|| format!("cannot parse svg at {}", path.display()))?;

    let escaped = escape_rust_string(&body);
    writeln!(
        out,
        "pub static {ident}: ::rune::Icon = ::rune::Icon {{\n    \
            name: \"{stem}\",\n    \
            view: {view:?}f32,\n    \
            body: \"{escaped}\",\n\
         }};",
    )?;
    Ok(())
}

fn to_screaming_snake(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            '-' | '.' => '_',
            c => c.to_ascii_uppercase(),
        })
        .collect()
}

fn escape_rust_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(c),
        }
    }
    out
}

fn parse_svg(svg: &str) -> Option<(f32, String)> {
    let svg_start = svg.find("<svg")?;
    let open_end = find_tag_end(svg, svg_start)?;
    let open_tag = &svg[svg_start..open_end];

    let view_box = extract_attr(open_tag, "viewBox")?;
    let parts: Vec<f32> = view_box
        .split(|c: char| c.is_whitespace() || c == ',')
        .filter(|s| !s.is_empty())
        .filter_map(|s| s.parse().ok())
        .collect();
    if parts.len() != 4 {
        return None;
    }
    let view = parts[2];

    let close = svg.rfind("</svg>")?;
    if close < svg_start {
        return None;
    }
    let body = &svg[svg_start..close + "</svg>".len()];
    Some((view, body.trim().to_string()))
}

fn find_tag_end(s: &str, start: usize) -> Option<usize> {
    let bytes = s.as_bytes();
    let mut quote: Option<u8> = None;
    for (i, &b) in bytes.iter().enumerate().skip(start) {
        match quote {
            Some(q) if b == q => quote = None,
            Some(_) => {}
            None => match b {
                b'"' | b'\'' => quote = Some(b),
                b'>' => return Some(i),
                _ => {}
            },
        }
    }
    None
}

fn extract_attr(tag: &str, name: &str) -> Option<String> {
    let pattern = format!("{name}=");
    let idx = tag.find(&pattern)?;
    let after = &tag[idx + pattern.len()..];
    let quote = after.chars().next()?;
    if quote != '"' && quote != '\'' {
        return None;
    }
    let rest = &after[1..];
    let end = rest.find(quote)?;
    Some(rest[..end].to_string())
}
